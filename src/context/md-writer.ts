import fs from "node:fs";
import path from "node:path";
import {
	INJECTION_MARKER_CONTEXT,
	INJECTION_TOPICS_PREFIX,
} from "../session/parser";
import type { ConversationMessage } from "../types";
import { debug } from "../utils/logger";
import { sanitizeId } from "../utils/sanitize";

const CONVERSATIONS_DIR = path.join(
	process.env.HOME ?? process.cwd(),
	".openclaw/workspace/memory/teams-conversations",
);

export function ensureConversationsDir(): void {
	if (!fs.existsSync(CONVERSATIONS_DIR)) {
		fs.mkdirSync(CONVERSATIONS_DIR, { recursive: true });
	}
}

function formatMessageMeta(
	meta?: Record<string, string | number | undefined>,
): string {
	if (!meta) return "";
	const parts: string[] = [];
	if (meta.teamsMessageId) parts.push(`msg:${meta.teamsMessageId}`);
	if (meta.replyToId && meta.replyToId !== meta.teamsMessageId) {
		parts.push(`replyTo:${meta.replyToId}`);
	}
	if (meta.senderName) parts.push(`by:${meta.senderName}`);
	if (meta.hasAttachments === "true" || Number(meta.hasAttachments) > 0) {
		parts.push("attachments:yes");
	}
	if (meta.hasMessageReference === "true") parts.push("threadReply:yes");
	return parts.join(" · ");
}

function truncatePreview(text: string, maxLen: number): string {
	return text.length > maxLen ? `${text.substring(0, maxLen)}...` : text;
}

function previewUserMessages(
	messages: ConversationMessage[],
	maxTopics: number,
	previewLength: number,
): string[] {
	return messages
		.filter((m) => m.role === "user")
		.slice(-maxTopics)
		.map((m) => truncatePreview(m.text.trim(), previewLength) || "(empty)");
}

function countParticipants(messages: ConversationMessage[]): number {
	const senders = new Set<string>();
	for (const m of messages) {
		if (m.metadata?.senderName) senders.add(m.metadata.senderName);
		else if (m.role === "user") senders.add("User");
		else senders.add("Rubot");
	}
	return senders.size;
}

export function saveConversationMd(
	conversationId: string,
	messages: ConversationMessage[],
): void {
	ensureConversationsDir();

	const safeId = sanitizeId(conversationId);
	const file = path.join(CONVERSATIONS_DIR, `${safeId}.md`);
	const now = new Date();
	const topics = getConversationTopics(messages, 10, 80);

	const lines: string[] = [];
	lines.push("# Teams Conversation");
	lines.push("");
	lines.push("| Field | Value |");
	lines.push("|-------|-------|");
	lines.push(`| **Thread** | \`${conversationId}\` |`);
	lines.push(`| **Last Active** | ${now.toISOString()} |`);
	lines.push(`| **Messages** | ${messages.length} |`);
	lines.push(`| **Participants** | ${countParticipants(messages)} |`);
	lines.push("");

	if (topics.length > 0) {
		lines.push("## Topics");
		lines.push("");
		topics.forEach((topic, i) => {
			lines.push(`${i + 1}. ${topic}`);
		});
		lines.push("");
	}

	lines.push("## Message History");
	lines.push("");

	for (const msg of messages) {
		const time = msg.timestamp
			? new Date(msg.timestamp).toLocaleString("id-ID", {
					timeZone: "Asia/Bangkok",
					day: "numeric",
					month: "short",
					year: "numeric",
					hour: "2-digit",
					minute: "2-digit",
				})
			: "";

		const meta = formatMessageMeta(msg.metadata);

		if (msg.role === "user") {
			lines.push(`### 👤 User · ${time}`);
		} else {
			lines.push(`### 🤖 Rubot · ${time}`);
		}

		if (meta) {
			lines.push(`**Meta:** \`${meta}\``);
		}

		lines.push("");
		lines.push(msg.text);
		lines.push("");
		lines.push("---");
		lines.push("");
	}

	lines.push(`> _Auto-generated by Rubot · ${now.toISOString()}_`);

	fs.writeFileSync(file, lines.join("\n"));
	debug(`Saved conversation MD: ${file}`);
}

export function getConversationTopics(
	messages: ConversationMessage[],
	maxTopics = 5,
	previewLength = 50,
): string[] {
	return previewUserMessages(messages, maxTopics, previewLength);
}

export function buildContextReference(
	conversationId: string,
	messages: ConversationMessage[],
): string {
	if (!messages?.length) return "";

	const safeId = sanitizeId(conversationId);
	const topics = getConversationTopics(messages, 5);

	if (topics.length === 0 || topics.every((t) => t === "(empty)")) return "";

	const mdPath = `~/.openclaw/workspace/memory/teams-conversations/${safeId}.md`;
	const msgCount = messages.length;

	const lines: string[] = [];
	lines.push(
		`${INJECTION_MARKER_CONTEXT} [${msgCount} msgs] Context: ${mdPath}`,
	);
	lines.push(`${INJECTION_TOPICS_PREFIX} ${topics.join(" · ")}`);
	lines.push("");

	return lines.join("\n");
}

export function cleanupOldConversations(maxAgeDays: number): void {
	const cutoff = Date.now() - maxAgeDays * 24 * 60 * 60 * 1000;

	try {
		for (const file of fs.readdirSync(CONVERSATIONS_DIR)) {
			if (!file.endsWith(".md")) continue;

			const stat = fs.statSync(path.join(CONVERSATIONS_DIR, file));
			if (stat.mtimeMs < cutoff) {
				fs.unlinkSync(path.join(CONVERSATIONS_DIR, file));
				debug(`Cleaned old conversation MD: ${file}`);
			}
		}
	} catch {
		// Directory might not exist yet
	}
}
